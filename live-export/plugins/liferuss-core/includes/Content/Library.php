	/**
	 * One page definition.
	 *
	 * @param string            $slug     Slug.
	 * @param string            $parent_slug Parent slug.
	 * @param string            $title    Title.
	 * @param string            $eyebrow  Eyebrow.
	 * @param string            $lead     Intro.
	 * @param string            $content  HTML.
	 * @param array<int, array> $sections Title/body pairs.
	 * @param array<int, array> $faqs     Question/answer pairs.
	 * @return array<string, mixed>
	 */
	private static function row( string $slug, string $parent_slug, string $title, string $eyebrow, string $lead, string $content, array $sections, array $faqs ): array {
		$blocks = array();
		foreach ( $sections as $section ) {
			$blocks[] = array(
				'title' => (string) $section[0],
				'body'  => (string) $section[1],
			);
		}
		$pairs = array();
		foreach ( $faqs as $faq ) {
			$pairs[] = array(
				'q' => (string) $faq[0],
				'a' => (string) $faq[1],
			);
		}
		return array(
			'slug'     => $slug,
			'parent'   => $parent_slug,
			'title'    => $title,
			'eyebrow'  => $eyebrow,
			'lead'     => $lead,
			'content'  => $content,
			'sections' => $blocks,
			'faqs'     => $pairs,
		);
	}
